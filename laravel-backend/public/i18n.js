let currentLang = localStorage.getItem('subarnapasal.lang') || 'en';

function t(key) {
  return I18N[currentLang]?.[key] ?? I18N.en[key] ?? key;
}

function setLanguage(lang) {
  currentLang = lang === 'ne' ? 'ne' : 'en';
  localStorage.setItem('subarnapasal.lang', currentLang);
  document.documentElement.lang = currentLang;
}

function categorySlug(name) {
  const slug = String(name || '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '');
  return slug || 'other';
}

const DEFAULT_ITEM_CATEGORIES = ['Gold', 'Silver', 'Other'];

const BUILTIN_CATEGORY_I18N = {
  gold: 'catGold',
  silver: 'catSilver',
  other: 'catOther',
  ring: 'catRing',
  necklace: 'catNecklace',
  bangle: 'catBangle',
  earring: 'catEarring',
  coin: 'catCoin',
  bar: 'catBar'
};

let itemCategoryNames = [...DEFAULT_ITEM_CATEGORIES];

function setItemCategoryNames(names) {
  itemCategoryNames = Array.isArray(names) && names.length
    ? [...names]
    : [...DEFAULT_ITEM_CATEGORIES];
}

function categoryOptionLabel(name) {
  const key = BUILTIN_CATEGORY_I18N[categorySlug(name)];
  return key ? t(key) : name;
}

function categoryLabel(cat) {
  const slug = String(cat || '').trim().toLowerCase();
  const key = BUILTIN_CATEGORY_I18N[slug];
  if (key) return t(key);
  const match = itemCategoryNames.find((n) => categorySlug(n) === slug);
  if (match) return match;
  return cat || t('catOther');
}

function applyStaticI18n() {
  document.querySelectorAll('[data-i18n]:not([data-currency-field])').forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-option]').forEach((el) => {
    el.textContent = t(el.dataset.i18nOption);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const text = t(el.dataset.i18nTitle);
    el.title = text;
    el.setAttribute('aria-label', text);
  });
  const langSelect = document.getElementById('language-select');
  if (langSelect) langSelect.value = currentLang;
}

